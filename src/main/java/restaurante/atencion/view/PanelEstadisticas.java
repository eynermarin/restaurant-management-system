    public PanelEstadisticas() {
        initComponents();
        // Fechas con formato día/mes/año; por defecto, los últimos 30 días
        spnDesde.setEditor(new javax.swing.JSpinner.DateEditor(spnDesde, "dd/MM/yyyy"));
        spnHasta.setEditor(new javax.swing.JSpinner.DateEditor(spnHasta, "dd/MM/yyyy"));
        spnDesde.setValue(aDate(LocalDate.now().minusDays(30)));
        spnHasta.setValue(aDate(LocalDate.now()));
    }

    /** Lo llama la ventana principal al arrancar. */
    public void setControlador(ControladorEstadisticas controlador) {
        this.controlador = controlador;
        javax.swing.DefaultComboBoxModel<Object> consultas = new javax.swing.DefaultComboBoxModel<>();
        for (ConsultaEstadistica c : controlador.consultas()) {
            consultas.addElement(c);
        }
        cmbConsulta.setModel(consultas);
        refrescar();
    }

    /** Vuelve a calcular la consulta elegida, por si hay visitas cerradas nuevas. */
    public void refrescar() {
        if (controlador == null) return; // la ventana aún se está armando
        consultar();
    }

    private void consultar() {
        ModeloTablaEstadisticas modelo = (ModeloTablaEstadisticas) tblResultados.getModel();
        try {
            spnDesde.commitEdit();
            spnHasta.commitEdit();
        } catch (java.text.ParseException e) {
            // fecha escrita mal: el spinner conserva la última fecha válida
        }
        try {
            ResultadoEstadistica r = controlador.calcular(cmbConsulta.getSelectedItem(),
                    (Date) spnDesde.getValue(), (Date) spnHasta.getValue());
            modelo.setResultado(r);
            if (r.estaVacio()) {
                lblResumen.setText("No hay datos en ese rango de fechas. Pruebe con un rango más amplio.");
            } else {
                lblResumen.setText(r.getResumen());
            }
            lblExplicacion.setText("<html>Cómo se calcula: "
                    + controlador.explicar(cmbConsulta.getSelectedItem()) + "</html>");
        } catch (RuntimeException e) {
            modelo.limpiar();
            lblResumen.setText(" ");
            javax.swing.JOptionPane.showMessageDialog(this, e.getMessage(), "Consulta inválida",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
        }
    }

    private static Date aDate(LocalDate fecha) {
        return Date.from(fecha.atStartOfDay(ZoneId.systemDefault()).toInstant());
    }

