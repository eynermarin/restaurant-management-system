    private void pestanasStateChanged(javax.swing.event.ChangeEvent evt) {//GEN-FIRST:event_pestanasStateChanged
        // Al cambiar de pestaña se recargan los datos, por si se cambiaron en otra.
        panelAdministracion.refrescar();
        panelBusqueda.refrescar();
        panelRecomendaciones.refrescar();

        if (panelMesas != null) {
            panelMesas.refrescar();
        }

        if (panelPedidos != null) {
            panelPedidos.refrescar();
        }

        if (panelCuenta != null) {
            panelCuenta.refrescar();
        }

        if (panelEstadisticas != null) {
            panelEstadisticas.refrescar();
        }
    }//GEN-LAST:event_pestanasStateChanged

